# Multi-Tier Web Application using Docker, Nginx and AWS EC2
## Project Overview
Built and deployed a multi-tier web application using Docker, Nginx, backend APIs, and AWS EC2.
---
## Architecture
Client Browser->Nginx Container->Backend API Container->Local JSON Storage
---
## Technologies Used
- HTML
- CSS
- Node.js
- Express.js
- Docker
- Nginx
- AWS EC2
- GitHub

